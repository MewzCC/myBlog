async(page)=>{
  await page.setViewportSize({width:390,height:844})
  await page.goto('http://127.0.0.1:4173/')
  await page.getByRole('button',{name:/跳过开场/}).click()
  await page.getByRole('button',{name:/出发，环岛兜风/}).click()
  const cdp=await page.context().newCDPSession(page)
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:2})
  const disc=page.getByRole('group',{name:'驾驶摇杆圆盘'})
  const r=await disc.boundingBox(),x=r.x+r.width/2,y=r.y+r.height/2
  const send=(type,px=x,py=y)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:type==='touchEnd'?[]:[{x:px,y:py,id:1}]})
  const read=()=>page.locator('canvas').evaluate(c=>({x:+c.dataset.x,z:+c.dataset.z,yaw:+c.dataset.yaw,speed:+c.dataset.speed}))
  await send('touchStart');await send('touchMove',x,y-r.width*.32)
  await page.waitForTimeout(950)
  const forward=await read()
  await send('touchEnd');await page.waitForFunction(()=>+document.querySelector('canvas').dataset.speed===0)
  if(forward.z<10||forward.speed<10)throw new Error('Touch forward failed')
  if(await disc.locator('.drift__joystick-thumb').evaluate(e=>getComputedStyle(e).transform)!=='matrix(1, 0, 0, 1, 0, 0)')throw new Error('Thumb did not recenter')
  await page.keyboard.press('KeyR');await page.waitForTimeout(300)
  await send('touchStart');await send('touchMove',x,y+r.width*.32)
  await page.waitForTimeout(950)
  const reverse=await read()
  await send('touchEnd');await page.waitForFunction(()=>+document.querySelector('canvas').dataset.speed===0)
  if(reverse.z>7)throw new Error('Touch reverse failed')
  await page.keyboard.press('KeyR');await page.waitForTimeout(300)
  await send('touchStart');await send('touchMove',x-25,y-30)
  await page.waitForTimeout(950)
  const left=await read();await send('touchEnd')
  if(left.x<.1||left.yaw<.05)throw new Error('Touch left failed')
  await page.keyboard.press('KeyR');await page.waitForTimeout(850)
  await send('touchStart');await send('touchMove',x+25,y-30)
  await page.waitForTimeout(950)
  const right=await read();await send('touchEnd')
  if(right.x>-.1||right.yaw>-.05)throw new Error('Touch right failed')
  await page.waitForFunction(()=>+document.querySelector('canvas').dataset.speed===0)
  await page.keyboard.press('KeyR')
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:false})
  await cdp.detach()
  await page.evaluate(v=>window.__joystickChecks=v,{forward,reverse,left,right,releaseStops:true})
}
