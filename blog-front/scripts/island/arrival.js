async (page) => {
  await page.setViewportSize({width:1440,height:1000})
  await page.goto('http://127.0.0.1:4173/')
  await page.getByRole('button',{name:/出发，环岛兜风/}).click()
  const read = () => page.evaluate(() => { const c=document.querySelector('canvas');return {x:+c.dataset.x,z:+c.dataset.z,yaw:+c.dataset.yaw,speed:+c.dataset.speed} })
  async function steerTo(x,z) {
    await page.keyboard.down('Space')
    await page.waitForFunction(()=>+document.querySelector('canvas').dataset.speed===0)
    const s=await read(),target=Math.atan2(x-s.x,z-s.z),diff=Math.atan2(Math.sin(target-s.yaw),Math.cos(target-s.yaw))
    const key=diff>0?'KeyA':'KeyD'
    await page.keyboard.down(key)
    await page.waitForFunction(t=>{const y=+document.querySelector('canvas').dataset.yaw;return Math.abs(Math.atan2(Math.sin(t-y),Math.cos(t-y)))<.035},target,{timeout:40000})
    await page.keyboard.up(key)
    await page.keyboard.up('Space')
  }
  await page.keyboard.down('KeyW')
  await page.waitForFunction(()=>+document.querySelector('canvas').dataset.z>14)
  await page.keyboard.up('KeyW')
  await steerTo(17,17)
  await page.keyboard.down('KeyW')
  await page.getByRole('complementary',{name:'路过站点提示'}).waitFor()
  if(await page.getByRole('dialog').count())throw new Error('Passing opened modal')
  await page.getByRole('button',{name:'暂停驾驶'}).click()
  await page.waitForTimeout(800)
  await page.screenshot({path:'D:/Project/myBlog/output/playwright/station-passing.png'})
  await page.getByRole('button',{name:'继续驾驶'}).click()
  await page.keyboard.down('KeyW')
  await page.waitForFunction(()=>{const c=document.querySelector('canvas');return Math.hypot(+c.dataset.x-17,+c.dataset.z-17)<3.4})
  await page.keyboard.up('KeyW')
  await page.keyboard.down('Space')
  await page.getByRole('dialog',{name:'书店 / 文章'}).waitFor({timeout:7000})
  await page.keyboard.up('Space')
  await page.waitForTimeout(850)
  const s=await read()
  if(s.speed!==0)throw new Error('Not stopped')
  await page.screenshot({path:'D:/Project/myBlog/output/playwright/station-parked.png'})
  const reel=page.locator('.drift__preview-reel')
  const start=await reel.evaluate(e=>getComputedStyle(e).transform)
  await page.waitForTimeout(600)
  const end=await reel.evaluate(e=>getComputedStyle(e).transform)
  if(start===end)throw new Error('Preview did not scroll')
  await page.locator('.drift__preview').hover()
  if(await reel.evaluate(e=>getComputedStyle(e).animationPlayState)!=='paused')throw new Error('Hover did not pause')
  await page.getByRole('button',{name:'关闭面板'}).click()
  await page.waitForTimeout(1300)
  if(await page.getByRole('dialog').count())throw new Error('Reopened after close')
  await page.evaluate(v => window.__arrivalChecks=v, {actualParking:s,passing:true,automatic:true,scroll:true,hoverPause:true,noReopen:true})
}
